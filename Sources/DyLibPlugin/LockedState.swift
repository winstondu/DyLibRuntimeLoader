import Foundation

/// Minimal mutex-guarded state box. NSLock keeps one portable code path for
/// Darwin and Linux (tests); contention here is negligible.
final class LockedState<Value>: @unchecked Sendable {
    private let lock = NSLock()
    private var value: Value

    init(_ value: Value) {
        self.value = value
    }

    func withLock<Result>(_ body: (inout Value) throws -> Result) rethrows -> Result {
        lock.lock()
        defer { lock.unlock() }
        return try body(&value)
    }
}
